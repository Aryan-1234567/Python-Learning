#classes are used to create objects in python
#example of a class

class Person:   #creating a class called Person
    name = "Aryan"  #creating an attribute called name and giving it a value of "Aryan"

a1 = Person()   #creating an object called a1 of class Person
print(a1.name)  # Output: Aryan

del a1 #deletes the object a1
del a1.name #deletes the attribute name of object a1

